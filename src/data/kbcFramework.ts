export const TOTAL_INDICATORS_COUNT = KBC_DIMENSIONS.reduce(
  (acc, dim) => acc + dim.indicators.length,
  0
); // 26 indicators
export const MAX_POSSIBLE_SCORE = TOTAL_INDICATORS_COUNT * 4; // 104 points

export function getScoreCategory(scorePercent: number): ScoreCategory {
  const found = SCORE_CATEGORIES.find(
    (c) => scorePercent >= c.minPercentage && scorePercent <= c.maxPercentage
  );
  return found || SCORE_CATEGORIES[SCORE_CATEGORIES.length - 1];
}
